"""
Planner Agent.

Takes an AgentGoal and produces a full execution plan:
  1. Parses goal_text with GPT to extract structured parameters
  2. Creates one Campaign
  3. Creates target_count ContentJobs (one per video)
  4. Creates target_count CampaignJobs linking campaign ↔ content
  5. Persists the plan to goal.plan_json and sets status → RUNNING
"""
from __future__ import annotations

import asyncio
import json
import logging
from datetime import datetime, timedelta, timezone

from sqlalchemy.ext.asyncio import AsyncSession

from app.content.repository import create_job as create_content_job
from app.content.schemas import ContentJobCreate
from app.campaign import repository as campaign_repo
from app.campaign.schemas import CampaignCreate, CampaignJobCreate
from app.campaign.models import PRIORITY_NORMAL
from . import repository as repo
from .knowledge import get_platform_defaults, estimate_campaign_duration
from .models import AgentGoal, GOAL_RUNNING, GOAL_FAILED, TASK_GENERATE_CONTENT, TASK_COMPLETED
from .reasoning import reason
from . import memory as mem

logger = logging.getLogger(__name__)


class PlannerAgent:
    """Turns an AgentGoal into a Campaign + jobs via existing infrastructure."""

    async def plan(self, db: AsyncSession, goal: AgentGoal) -> dict:
        """
        Main entry point. Returns the plan dict.
        Raises on unrecoverable errors (caller updates goal to FAILED).
        """
        logger.info("PlannerAgent: planning goal %d — '%s'", goal.id, goal.goal_text[:60])

        # Step 1: parse goal with GPT (or use provided fields)
        parsed = await self._parse_goal(goal)

        product = parsed.get("product") or goal.product or "Unknown Product"
        platform = parsed.get("platform") or goal.platform
        count = parsed.get("count") or goal.target_count
        audience = parsed.get("audience") or ""
        visual_style = parsed.get("visual_style") or ""

        defaults = get_platform_defaults(platform)

        # Step 2: create Campaign
        campaign = await campaign_repo.create_campaign(
            db,
            CampaignCreate(
                name=f"[AI] {goal.goal_text[:60]}",
                description=f"Auto-generated by Agent Goal #{goal.id}",
                platform_default=platform,
            ),
        )
        goal.campaign_id = campaign.id
        goal.tasks_total = count
        await db.commit()

        # Step 3: create ContentJobs + CampaignJobs
        content_jobs = []
        campaign_jobs = []
        for i in range(count):
            # ContentJob
            cj = await create_content_job(
                db,
                ContentJobCreate(
                    title=f"{product} – Video {i + 1}",
                    topic=goal.goal_text,
                    objective=f"Promote {product} on {platform}",
                    audience=audience or defaults.get("audience", ""),
                    product=product,
                    duration=defaults.get("content_duration", "15s"),
                    visual_style=visual_style,
                ),
            )
            content_jobs.append(cj)

            # CampaignJob
            pj = await campaign_repo.create_campaign_job(
                db,
                CampaignJobCreate(
                    campaign_id=campaign.id,
                    content_job_id=cj.id,
                    platform=platform,
                    priority=goal.priority,
                    retry_max=defaults.get("retry_max", 3),
                ),
            )
            campaign_jobs.append(pj)

        # Step 4: produce agent tasks (one GENERATE_CONTENT per ContentJob)
        for cj, pj in zip(content_jobs, campaign_jobs):
            await repo.create_task(
                db,
                goal_id=goal.id,
                task_type=TASK_GENERATE_CONTENT,
                agent="content",
                input_data={
                    "content_job_id": cj.id,
                    "campaign_job_id": pj.id,
                    "product": product,
                    "platform": platform,
                },
            )

        # Step 5: record reasoning
        r = await reason(
            context=(
                f"Goal: {goal.goal_text}\n"
                f"Platform: {platform}, Product: {product}, Count: {count}\n"
                f"Available devices: unknown at this stage"
            ),
            options=["proceed_with_plan", "request_more_info"],
            agent_name="planner",
        )
        await repo.record_decision(
            db,
            agent="planner",
            decision=r.decision,
            reason=r.reason,
            confidence=r.confidence,
            alternative=r.alternative,
            expected_result=r.expected_result,
            goal_id=goal.id,
            was_failsafe=r.was_failsafe,
        )

        estimate = estimate_campaign_duration(count, platform)
        plan = {
            "campaign_id": campaign.id,
            "product": product,
            "platform": platform,
            "count": count,
            "content_jobs": [c.id for c in content_jobs],
            "campaign_jobs": [p.id for p in campaign_jobs],
            "estimated_duration": estimate,
            "planning_confidence": r.confidence,
            "created_at": datetime.now(timezone.utc).isoformat(),
        }

        await repo.update_goal_plan(db, goal, plan)
        await repo.update_goal_status(db, goal, GOAL_RUNNING)

        # Store in memory
        await mem.remember(
            db,
            key=f"plan:goal:{goal.id}",
            category="campaign",
            value=plan,
            summary=f"Plan for goal {goal.id}: {count}x {platform} for {product}",
        )

        logger.info(
            "PlannerAgent: goal %d → campaign %d, %d jobs created",
            goal.id, campaign.id, count,
        )
        return plan

    async def _parse_goal(self, goal: AgentGoal) -> dict:
        """
        Use GPT to extract structured parameters from free-text goal.
        Falls back gracefully if GPT unavailable.
        """
        from app.core.config import settings
        if not settings.openai_api_key:
            return {
                "product": goal.product,
                "platform": goal.platform,
                "count": goal.target_count,
                "audience": "",
                "visual_style": "",
            }

        prompt = f"""Extract campaign parameters from this goal text.

Goal: "{goal.goal_text}"

Known values:
- platform: "{goal.platform}"
- product: "{goal.product}"
- count: {goal.target_count}

Return JSON:
{{
  "product": "product name (string)",
  "platform": "tiktok or youtube_create",
  "count": number of videos/jobs (integer, respect the known count unless goal says otherwise),
  "audience": "target audience description",
  "visual_style": "visual style preference if mentioned"
}}

JSON only."""

        try:
            result = await asyncio.to_thread(self._call_gpt, prompt)
            data = json.loads(result)
            # Clamp count to reasonable range
            data["count"] = max(1, min(int(data.get("count", goal.target_count)), 500))
            return data
        except Exception as exc:
            logger.warning("PlannerAgent: goal parse failed (%s), using defaults", exc)
            return {
                "product": goal.product,
                "platform": goal.platform,
                "count": goal.target_count,
                "audience": "",
                "visual_style": "",
            }

    @staticmethod
    def _call_gpt(prompt: str) -> str:
        from app.services.ai_generator import _client
        from app.core.config import settings
        resp = _client().chat.completions.create(
            model=settings.openai_model,
            messages=[{"role": "user", "content": prompt}],
            max_tokens=200,
            temperature=0.2,
            response_format={"type": "json_object"},
        )
        return resp.choices[0].message.content


planner_agent = PlannerAgent()
